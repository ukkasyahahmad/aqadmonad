// Generates web/contracts/deployedContracts.ts from Foundry output, keyed by chain ID.
// Sources: contracts/broadcast/Deploy.s.sol/<chainId>/run-latest.json (local forge script)
//          contracts/deployments/<chainId>.json (testnet CreateX deploy, written by deploy-testnet.sh)
// Usage: node scripts/export-contracts.mjs
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "contracts");
const NAMES = ["AuctionHouse", "DemoNFT"];
const abi = (name) => JSON.parse(readFileSync(join(root, "out", `${name}.sol`, `${name}.json`), "utf8")).abi;

const chains = {};

const bdir = join(root, "broadcast", "Deploy.s.sol");
if (existsSync(bdir)) {
  for (const chainId of readdirSync(bdir)) {
    const f = join(bdir, chainId, "run-latest.json");
    if (!existsSync(f)) continue;
    const run = JSON.parse(readFileSync(f, "utf8"));
    const entry = {};
    for (const tx of run.transactions) {
      if (tx.transactionType !== "CREATE" || !NAMES.includes(tx.contractName)) continue;
      const receipt = run.receipts.find((r) => r.transactionHash === tx.hash);
      entry[tx.contractName] = { address: tx.contractAddress, deployedOnBlock: Number(BigInt(receipt.blockNumber)) };
    }
    chains[chainId] = entry;
  }
}

const ddir = join(root, "deployments");
if (existsSync(ddir)) {
  for (const file of readdirSync(ddir).filter((f) => f.endsWith(".json"))) {
    chains[file.replace(".json", "")] = JSON.parse(readFileSync(join(ddir, file), "utf8"));
  }
}

const out = {};
for (const [chainId, entry] of Object.entries(chains)) {
  out[chainId] = {};
  for (const name of NAMES) {
    if (!entry[name]) throw new Error(`chain ${chainId}: missing ${name}`);
    out[chainId][name] = { ...entry[name], abi: abi(name) };
  }
}

const ts = `// AUTO-GENERATED by scripts/export-contracts.mjs — do not edit by hand.
const deployedContracts = ${JSON.stringify(out, null, 2)} as const;

export default deployedContracts;
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), "..", "contracts", "deployedContracts.ts"), ts);
console.log("Exported chains:", Object.entries(out).map(([c, e]) => `${c} (AuctionHouse ${e.AuctionHouse.address})`).join(", "));
